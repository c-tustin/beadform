// Generate local-only JavaScriptCore resources from the production flat compiler.
import {readFileSync,writeFileSync} from 'node:fs';
const root=new URL('../../',import.meta.url),out=new URL('../ios/Beadform/Resources/',import.meta.url);
let bundle='// Generated by app/scripts/bundle-pattern-engine.mjs. Do not edit.\n';
for(const file of ['engine.js','shape-engine.js','pattern-quality.js','stitch-programs.mjs','pattern-checker.mjs']){
 let source=readFileSync(new URL(file,root),'utf8');
 if(file==='stitch-programs.mjs')source=source.slice(0,source.indexOf('if(process.argv[1]'));
 source=source.replace(/^import .*;\n/gm,'').replace(/^export /gm,'');
 bundle+='\n// '+file+'\n'+source+'\n';
}
bundle+=`
globalThis.mobileCompile = function(json) {
 const r=JSON.parse(json);
 const p=compileRecipe(r);
 if(p.needsClarification)throw Error('Please specify a supported flat stitch and dimensions.');
 const checker=checkPattern(p,{requireSelection:false});
 if(!checker.passed)throw Error(checker.issues.filter(i=>i.severity==='error').map(i=>i.message).join(' '));
 const words=o=>o.kind==='thread-bridge'?'Go under the existing thread bridge between '+o.between.join(' and ')+'.':o.kind==='pick'?'Pick up new bead '+o.id+'.':'Pass through existing bead '+o.id+'.';
 const ys=[...new Set(p.beads.map(b=>b.yMm))].sort((a,b)=>a-b);
 return JSON.stringify({title:r.stitch+' '+r.shape,technique:r.stitch,source:'on-device-qwen',rows:ys.map(y=>p.beads.filter(b=>b.yMm===y).sort((a,b)=>a.xMm-b.xMm).map(b=>b.id)),beadPositions:p.beads.map(b=>({id:b.id,x:b.xMm,y:b.yMm})),steps:p.steps.map(s=>s.label+'\\n'+s.operations.map(words).join('\\n')),checker:checker.status});
};
`;
writeFileSync(new URL('pattern-engine.js',out),bundle);
writeFileSync(new URL('stitch-system.json',out),readFileSync(new URL('training/local-image-system.json',root)));
writeFileSync(new URL('model-manifest.json',out),readFileSync(new URL('training/local-image-runtime.json',root)));
